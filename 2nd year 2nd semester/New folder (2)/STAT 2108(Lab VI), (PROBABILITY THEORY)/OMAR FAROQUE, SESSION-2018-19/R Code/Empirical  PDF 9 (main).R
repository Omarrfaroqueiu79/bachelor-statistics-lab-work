#################################################
#####  Cubic Transmuted LIndley Distribution  ###
#################################################



l= 0.99999997 
t= 0.04301065




g1= (t^2)/(t+1)
g2= exp(-t*x)

g= g1* (1+x) * g2  # Base Distribution PDF #


G1= (t+1+(t*x))/(t+1)

G = 1- (G1*g2)   # Base Distribution CDF #



f1= (1-l) * g
f2= 6*l*g*G
f3= 6*l*g*(G^2)

fx = f1 + f2 - f3 # Cubic Distribution PDF #




lines(x,fx,type="l", col="red", lty=6, lwd=2)



#############################################
###### Transmuted LIndley Distribution ######
#############################################


t =  0.06443516
l = -0.99999969 


f1= t^2

f2= f1/(t+1)
f3= (1+x)*exp(-t*x)
f4= (t+1+t*x)/(t+1)

fx= f2* f3* (1-l + 2*l*f4*exp(-t*x))



lines(x,fx,type="l",col="green4", lty=5,lwd=2)

