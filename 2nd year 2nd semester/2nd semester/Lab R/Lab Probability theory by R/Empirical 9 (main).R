      24.32, 55.88, 31.74, 76.17)


v= sort(x)

x=v
hist(x)




#########################################
### Cubic Transmuted Empirical CDF ######
#########################################


ecdf(x)
plot.stepfun(ecdf(x),main = "",
             xlab = "x ", ylab = "Fn(x)" , col.vert = "blue",col = "blue",cex=0.001,lwd=2)

##############################
### Cubic Transmuted CDF #####
##############################

l= 0.99999997 
t= 0.04301065

g1= (t^2)/(t+1)
g2= exp(-t*x)

g= g1* (1+x) * g2  # Base Distribution PDF #


G1= (t+1+(t*x))/(t+1)

G = 1- (G1*g2)   # Base Distribution CDF #


F1 = (1-l)* G
F2 = 3*l*(G^2) 
F3 = 2*l*(G^3) 

Fx1 = F1 +F2 - F3 # Cubic Distribution CDF #

lines(x,Fx1,col="red",lty=1,lwd=2.5)

#############################
#####  Transmuted CDF #######
#############################

t =  0.06443516
l = -0.99999969 


F1 = (t+1+t*x)/(t+1)
F2= F1*exp(-t*x)

Fx2 = (1-F2)*(1+l*F2)



lines(x,Fx2,col="black",lty=2,lwd=2.5)

